from __future__ import annotations


def owner_block(rules: list[str], lessons: list[str] | None = None) -> str:
    out = "ПРАВИЛА ВЛАДЕЛЬЦА (обязательны):\n" + "\n".join(f"- {r}" for r in rules)
    if lessons:
        out += "\n\nУРОКИ ИЗ ПРОШЛЫХ ЗАДАЧ (плейбук):\n" + "\n".join(f"- {x}" for x in lessons)
    return out


